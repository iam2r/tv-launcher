    /**
     * A theme's full-screen picture behind everything. Decoded once at the size CENTER_CROP shows, so it
     * costs a screen-sized bitmap (about 4 MB at 1080p), which is the price of a wallpaper on a 1 GB TV.
     * A picture over 4K is refused rather than decoded (#166); the plain colour stays.
     */
    private void showWallpaper(File file) {
        try {
            android.util.DisplayMetrics dm = getResources().getDisplayMetrics();
            android.graphics.BitmapFactory.Options opts = new android.graphics.BitmapFactory.Options();
            opts.inJustDecodeBounds = true;
            android.graphics.BitmapFactory.decodeFile(file.getPath(), opts);
            int w = opts.outWidth, h = opts.outHeight;
            if (w <= 0 || h <= 0) return;
            int sample = WallpaperSize.sampleSize(w, h, dm.widthPixels, dm.heightPixels);
            // The limit applies to what is decoded, so a 12 MP photo still works once it is sampled down.
            if (!WallpaperSize.accepted(w / sample, h / sample)) return;
            opts.inJustDecodeBounds = false;
            opts.inSampleSize = sample;
            int[] scale = WallpaperSize.coverScale(w / sample, h / sample, dm.widthPixels, dm.heightPixels);
            if (scale != null) {
                opts.inScaled = true;
                opts.inDensity = scale[0];
                opts.inTargetDensity = scale[1];
            }
            opts.inPreferredConfig = android.graphics.Bitmap.Config.RGB_565;   // no alpha needed, half the memory
            android.graphics.Bitmap bmp = android.graphics.BitmapFactory.decodeFile(file.getPath(), opts);
            if (bmp == null) return;
            android.widget.ImageView wall = new android.widget.ImageView(this);
            wall.setScaleType(android.widget.ImageView.ScaleType.CENTER_CROP);
            wall.setImageBitmap(bmp);
            root.addView(wall, 0, new FrameLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT));
        } catch (Exception | OutOfMemoryError e) {
            // A bad or huge picture must never take the home screen down; the plain colour stays.
        }
    }

    /**
     * Home pressed while Home is already in front: singleTask delivers it here, then onResume runs.
     * Back to the top with the first dock tile focused, like the stock launcher. Back from an app
     * never comes this way, so returning to the app you left from is unchanged (#118).
     */
    @Override
    protected void onNewIntent(Intent intent) {
        super.onNewIntent(intent);
        if (openLauncherSettingsIfAsked(intent)) return;
        if (intent == null || !intent.hasCategory(Intent.CATEGORY_HOME)) return;
        grid.scrollToPosition(0);
        lastFocused = 0;
        lastFocusedKey = adapter.getItemCount() > 0 ? adapter.keyAt(0) : null;
        rebuildOnResume = true;
    }

    @Override
    protected void onStart() {
        super.onStart();
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
            registerReceiver(packageReceiver, packageFilter, Context.RECEIVER_NOT_EXPORTED);
        } else {
            registerReceiver(packageReceiver, packageFilter);
        }
    }

    /** The language choice this instance was built with; a different one in the panel rebuilds it. */
    private String appliedLangChoice = "";

    /**
     * The clock's format follows the panel, not the TV's system setting: 24-hour by default, 12-hour with
     * am/pm when the owner prefers it. It is a plain TextView redrawn here rather than a TextClock, because
     * a TextClock only picks up a new format on its next minute tick - the panel's choice looked ignored
     * until the minute happened to change.
     */
    private void applyClockFormat() {
        TextView clock = findViewById(R.id.clock);
        if (clock == null) return;
        boolean hour24 = getSharedPreferences(Config.SETTINGS_NAME, MODE_PRIVATE)
                .getBoolean(CLOCK_24H, true);
        SimpleDateFormat format = new SimpleDateFormat(hour24 ? "HH:mm" : "h:mm a", Lang.localeOf(this));
        clock.setText(format.format(new Date()));
    }

    /** Redraws the clock the moment the panel writes the choice, whether or not Home resumes next. */
    private final SharedPreferences.OnSharedPreferenceChangeListener clockPrefs =
            (prefs, key) -> {
                if (CLOCK_24H.equals(key)) applyClockFormat();
            };

    /** Posts the next minute tick aligned with the wall clock, so the clock and greeting never lag a minute. */
    private void scheduleMinuteTick() {
        handler.removeCallbacks(minuteTick);
        long now = System.currentTimeMillis();
        handler.postDelayed(minuteTick, MINUTE_MS - now % MINUTE_MS);
    }

    @Override
    protected void onResume() {
        super.onResume();
        promptsPaused = false;
        // The panel may have changed the clock or the language while Home was behind it.
        if (!Lang.chosen(this).equals(appliedLangChoice)) {
            recreate();
            return;
        }
        applyClockFormat();
        if (rebuildOnResume) {
            tilesReady = false;
            reloadApps(true);
        }
        rebuildOnResume = false;
        updateGreeting();
        updateWifiLabel();
        updateInputsButton();
        if (showStats) startStats();
        scheduleMinuteTick();
    }

    @Override
    protected void onActivityResult(int requestCode, int resultCode, Intent data) {
        super.onActivityResult(requestCode, resultCode, data);
        if (requestCode == LAUNCHER_SETTINGS_REQUEST && resultCode == RESULT_OK) recreate();
    }

    /** Rebuilds the tiles, then puts focus back where it was. */
    private void reloadApps(boolean animate) {
        cancelPendingFocusScroll();
        // Capture the app before rebinding can move focus and overwrite its key.
        final String returnKey = lastFocusedKey;
        final int returnSlot = lastFocused;
        final boolean restoreFocus = animate || grid.hasFocus();
        if (restoreFocus) {
            glassShown = false;
            glass.setAlpha(0f);
            heroShown = false;
            heroName.setAlpha(0f);
            ambient.setAlpha(0f);
        }
        reloadTiles();
        if (animate && animations && !reducedMotion) grid.scheduleLayoutAnimation();

        if (restoreFocus) {
            // Keep a focused footer at the end even when the app count changes.
            restoreFocus();
        } else {
            // A package change must not steal focus from a top button or the Inputs popup.
            int pos = adapter.positionOf(returnKey);
            lastFocused = Math.max(0, Math.min(pos >= 0 ? pos : returnSlot, adapter.appCount() - 1));
            lastFocusedKey = adapter.keyAt(lastFocused);
            if (pos < 0) hideHero();
            tilesReady = true;
        }
    }

    /** Rebuilds the tiles, keeping the focused one on its app. */
    private void reloadTiles() {
        if (reordering) endReorder();   // an app installed or removed while reordering: keep the order so far
        // Read these before reload(): rebinding can move focus to the first tile and overwrite them.
        final String returnKey = lastFocusedKey;
        final int returnSlot = lastFocused;
        if (shelfMode) adapter.setShelf(slots);
        adapter.reload();
        lastFocusedKey = returnKey;
        lastFocused = returnSlot;
    }

    /**
     * Return to the app we left from, or the same slot if that app is gone. Always refocus: after
     * reload() the view that holds focus may no longer show the app it had.
     */
    private void restoreFocus() {
        final String returnKey = lastFocusedKey;
        final int returnSlot = lastFocused;
        grid.post(() -> {
            int pos = adapter.positionOf(returnKey);
            focusTile(pos >= 0 ? pos : returnSlot);
            tilesReady = true;
        });
    }

    @Override
    protected void onPause() {
        super.onPause();
        endReorder();   // Home or another app while reordering keeps the order so far
        stopAmbientAnimation();
        heroName.animate().cancel();
        ambient.animate().cancel();
        handler.removeCallbacks(minuteTick);
        stopStats();
        cancelPendingFocusScroll();
        // Nothing of ours stays on screen over another app; an undecided prompt simply returns next time.
        if (openPopup != null) openPopup.dismiss();
        if (drawer != null) drawer.close();
        hideTopBarIfUnfocused();
    }

    @Override
    protected void onStop() {
        super.onStop();
        unregisterReceiver(packageReceiver);
        rebuildOnResume = true;
    }

    /**
     * Whether the focused view is one of the launcher's own (a tile, a toolbar pill, the Wi-Fi pill). A fresh
     * window often focuses the root layout instead, which silently swallows the first remote key.
     */
    private boolean focusIsOurs() {
        for (View v = getCurrentFocus(); v != null; ) {
            if (v == grid || v == topBar || v == btnWifi) return true;
            ViewParent parent = v.getParent();
            v = parent instanceof View ? (View) parent : null;
        }
        return false;
    }

    @Override
    public void onWindowFocusChanged(boolean hasFocus) {
        super.onWindowFocusChanged(hasFocus);
        if (hasFocus) {
            // Nothing of ours had real focus yet (first start, or whatever held it went away): the remote
            // would drop the first key, an Up on Home included. Give a tile focus as soon as the grid can take it.
            if (!focusIsOurs()) {
                grid.post(() -> {
                    if (focusIsOurs() || adapter == null || isFinishing()) return;
                    int count = adapter.appCount();
                    focusTile(count == 0 ? 0 : Math.max(0, Math.min(lastFocused, count - 1)));
                });
            }
        }
    }

