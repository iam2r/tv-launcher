    /**
     * A shelf Home parks its one row low, with the rest of the screen empty above it.
     *
     * <p>This is done by a spacer with the leftover weight above the grid, not by the grid's top padding: a
     * padding set from an onLayoutChange callback only exists from the second layout pass on, which showed
     * as the row sitting under the clock for a moment and then dropping into place when Home started.
     */
    private void placeShelfRow(boolean shelf) {
        View wrapper = findViewById(R.id.gridWrapper);
        if (wrapper == null || grid == null || !(wrapper.getParent() instanceof LinearLayout)) return;
        LinearLayout column = (LinearLayout) wrapper.getParent();
        if (!shelf) return;
        LinearLayout.LayoutParams wrapLp = (LinearLayout.LayoutParams) wrapper.getLayoutParams();
        wrapLp.height = LinearLayout.LayoutParams.WRAP_CONTENT;
        wrapLp.weight = 0f;
        wrapLp.bottomMargin = Math.round(AppAdapter.SLOT_BOTTOM_ROOM_DP * getResources().getDisplayMetrics().density);
        wrapper.setLayoutParams(wrapLp);
        // The grid's own bottom padding (for the scrollable Home) would lift the row again.
        grid.setPadding(grid.getPaddingLeft(), grid.getPaddingTop(), grid.getPaddingRight(), 0);
        if (wrapper.getTag(R.id.gridWrapper) == null) {
            Space spacer = new Space(this);
            spacer.setTag(Integer.valueOf(1));
            column.addView(spacer, column.indexOfChild(wrapper),
                    new LinearLayout.LayoutParams(LinearLayout.LayoutParams.MATCH_PARENT, 0, 1f));
            wrapper.setTag(R.id.gridWrapper, spacer);
        }
    }

